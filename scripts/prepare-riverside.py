"""Package the already verified Riverside crop; never modify its Gaussian records.

The 4x4 display-unit height proxy is an opacity-weighted local median, used
only by water/placement/camera rules. It is not measured physical terrain.
Run from the worktree root. All inputs are existing local files; no download.
"""
import hashlib
import json
import math
from pathlib import Path
import struct

root = Path(__file__).resolve().parents[1]
evidence = root / '.local/riverside-2026-10-03'
native = json.loads((evidence / 'native.json').read_text())
crop = evidence / 'ground-left.ply'
raw = crop.read_bytes()
assert hashlib.sha256(raw).hexdigest() == native['inputSha256']
end = raw.index(b'end_header\n') + len(b'end_header\n')
fields = [line.split()[-1] for line in raw[:end].decode().splitlines() if line.startswith('property float ')]
assert len(fields) == 59 and len(raw) - end == 64949 * 236
indices = {key: fields.index(key) for key in ['x', 'y', 'z', 'opacity']}
points = []
for values in struct.iter_unpack('<59f', raw[end:]):
    x, y, z, opacity = [values[indices[k]] for k in ['x', 'y', 'z', 'opacity']]
    points.append(((x + .265) * 13, (.05107251554727554 - y) * 13, -z * 13, 1 / (1 + math.exp(-opacity))))

buckets = {}
for x, y, z, opacity in points:
    buckets.setdefault((math.floor(x / .25), math.floor(z / .25)), []).append((x, y, z, opacity))
heights = []
for iz in range(41):
    for ix in range(41):
        x, z = ix * .1 - 2, iz * .1 - 2
        gx, gz = math.floor(x / .25), math.floor(z / .25)
        nearby = [p for dx in [-1, 0, 1] for dz in [-1, 0, 1] for p in buckets.get((gx + dx, gz + dz), []) if math.hypot(p[0] - x, p[2] - z) <= .25]
        assert nearby, (ix, iz)
        weighted = sorted((p[1], p[3] * math.exp(-((p[0] - x) ** 2 + (p[2] - z) ** 2) / .02)) for p in nearby)
        halfway = sum(w for _, w in weighted) / 2
        accumulated = 0
        for height, weight in weighted:
            accumulated += weight
            if accumulated >= halfway:
                heights.append(height)
                break

out = root / 'public/assets/riverside-ground-v1'
out.mkdir(parents=True, exist_ok=True)
outputs = []
for item in native['outputs']:
    data = (evidence / item['filename']).read_bytes()
    assert len(data) == item['bytes'] and hashlib.sha256(data).hexdigest() == item['sha256']
    name = 'riverside-' + item['key'] + '.u32'
    target = out / name
    assert not target.exists() or target.read_bytes() == data
    target.write_bytes(data)
    outputs.append({**item, 'filename': name})
license_bytes = (root / '.local/ground-assets/riverside-8f52baf1-v1/license.txt').read_bytes()
assert hashlib.sha256(license_bytes).hexdigest() == '9cb2dfea2bd6835bd3d60b35e579d336125662c7e2574ec84704ed305437f6bb'
(out / 'LICENSE.txt').write_bytes(license_bytes)
metadata = {
    'id': 'riverside-ground-v1', 'author': 'VeryOS', 'title': 'Riverside',
    'source': 'https://superspl.at/scene/8f52baf1', 'license': 'CC BY 4.0',
    'licenseUrl': 'https://creativecommons.org/licenses/by/4.0/',
    'changes': 'Continuous AABB crop, Spark 2.3.1 native SH3 quantization, whole-mesh X rotation180deg and uniform display scale13; no per-splat cleanup, tiling, recoloring or height deformation.',
    'sourcePlySHA256': '44e6e42ceaacec4b5fe79d3dbd78203416f6080225a81f15b9cb8199b5c39d8a',
    'cropSHA256': native['inputSha256'], 'count': 64949, 'shBands': 3,
    'capacity': 65536, 'scale': 13,
    'position': [.265 * 13, .05107251554727554 * 13, 0],
    'rotation': [1, 0, 0, 0], 'outputs': outputs,
    'heightProxy': {'width': 4, 'depth': 4, 'spacing': .1, 'nx': 41, 'nz': 41,
        'method': 'Opacity-weighted median within display radius0.25 with Gaussian distance weights; all source records retained for rendering. Not a physical collision surface.',
        'heights': heights},
}
(out / 'SOURCE.json').write_text(json.dumps(metadata, ensure_ascii=False, indent=2) + '\n')
(root / 'src/terrain/riverside-data.ts').write_text('// Generated by scripts/prepare-riverside.py from the verified local crop.\nexport const riversideData = ' + json.dumps(metadata, ensure_ascii=False, separators=(',', ':')) + ' as const;\n')
print(json.dumps({'count': 64949, 'nativeBytes': sum(o['bytes'] for o in outputs), 'heightCells': len(heights), 'heightRange': [min(heights), max(heights)], 'uniformDisplayScale': 13}))
