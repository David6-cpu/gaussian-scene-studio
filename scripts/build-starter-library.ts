/**
 * Builds the bundled starter library (starter-library/) from the project's own
 * procedural generators. Usage:
 *   node scripts/build-starter-library.ts --from .local/general-scene-library --out starter-library
 *
 * --from supplies the reviewed candidate geometry (bounds, support points,
 * footprint); point data is regenerated and must match the candidate hashes
 * byte for byte. The output directory must not exist yet.
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, resolve } from "node:path";
import { createHash } from "node:crypto";
import { makeRiverProps } from "../src/assets/river-props.ts";
import {
  parseAssetManifest,
  parseSurfaceStyle,
} from "../src/general-scene/asset-manifest.ts";
import {
  assetContentVersion,
  prepareAssetPackage,
} from "../src/general-scene/asset-package.ts";
import { styleContentVersion } from "../src/general-scene/asset-library.ts";
import {
  loadLibrary,
  registerAsset,
} from "../src/general-scene/asset-library-server.ts";
import { canonicalJson } from "../src/io/prepared-ground.ts";

const args = process.argv.slice(2);
if (args.length !== 4 || args[0] !== "--from" || args[2] !== "--out")
  throw Error("Usage: --from <candidate library dir> --out <new dir>");
const from = resolve(args[1]),
  out = resolve(args[3]);
if (existsSync(out)) throw Error(`${out} already exists`);

// Approval given by the project owner on 2026-10-19 after viewing the
// candidate inspection captures; see docs/validation/starter-library.md.
const REVIEWER = "Project owner";
const REVIEWED_AT = "2026-10-19T14:00:00.000Z";
const REPORT = "docs/validation/starter-library.md";
const LICENSE_ID = "project-starter-example";
const LICENSE_SUMMARY =
  "Starter example generated by this project's own procedural code. The project owner permits redistribution together with this project.";
const LICENSE_BASIS =
  "Original output of src/assets/river-props.ts; the project owner granted redistribution on 2026-10-19.";
const licenseText = (source: string, seed: number) =>
  `Gaussian Scene Studio starter example asset.\n` +
  `Procedurally generated by this project's own code (${source}, seed ${seed}).\n` +
  `Not captured from a real object; no species or real-world likeness is claimed.\n` +
  `The project owner permits redistributing this file together with this project.\n`;
const LIMITATIONS = [
  "Starter example: procedural stand-in, not a photographic capture.",
  "Approved from front/back/top/low inspection captures at the recorded cameras; other distances and angles were not separately reviewed.",
  "Bounds are numerical 3-sigma AABBs; Gaussian tails are unbounded.",
  "Contact error against uneven terrain is not measured; keep slopes gentle.",
];

const sha = (bytes: Uint8Array) =>
  createHash("sha256").update(bytes).digest("hex");
const bytesOf = (data: Float32Array) =>
  new Uint8Array(data.buffer, data.byteOffset, data.byteLength).slice();
const normalize = (v: number[]) => {
  const n = Math.hypot(...v);
  return v.map((x) => x / n) as [number, number, number];
};

const lowGrassCall = makeRiverProps(20261010, "low-grass"),
  reedCall = makeRiverProps(20261010, "reed");
const specs = [
  {
    candidate: "river-props-rock-seed20261010",
    id: "starter-rock-v1",
    category: "rock",
    environments: ["wetland", "forest", "grassland"],
    prop: lowGrassCall[0],
    kind: "low-grass",
  },
  {
    candidate: "river-props-low-grass-seed20261010",
    id: "starter-low-grass-v1",
    category: "grass",
    environments: ["wetland", "forest", "grassland"],
    prop: lowGrassCall[1],
    kind: "low-grass",
  },
  {
    candidate: "river-props-reed-seed20261010",
    id: "starter-reed-v1",
    category: "reed",
    environments: ["wetland"],
    prop: reedCall[1],
    kind: "reed",
  },
];

// Review cameras recorded by scripts/review-general-assets.mjs.
const reviewRun = join(
  resolve(from, ".."),
  "general-asset-reviews/2026-10-10T14-27-18.718Z/evidence.json",
);
const reviewEvidence = JSON.parse(readFileSync(reviewRun, "utf8"));

const reviewed: string[] = [];
for (const spec of specs) {
  const candidate = JSON.parse(
    readFileSync(join(from, spec.candidate, "manifest.json"), "utf8"),
  );
  const full = bytesOf(spec.prop.lods.full.data),
    coarse = bytesOf(spec.prop.lods.coarse!.data);
  if (
    sha(full) !== candidate.gaussian.full.sha256 ||
    sha(coarse) !== candidate.gaussian.coarse.sha256
  )
    throw Error(`${spec.candidate}: generator output no longer matches`);

  const cameras = reviewEvidence.assets
    .find((a: any) => a.ref.id === spec.candidate)
    .captures.filter((c: any) =>
      ["front", "back", "top", "low"].includes(c.view),
    )
    .map((c: any) => JSON.stringify(c.camera));
  const views = [...new Set<string>(cameras)].map((c) => JSON.parse(c));
  const minimum = reviewEvidence.assets
    .find((a: any) => a.ref.id === spec.candidate)
    .captures.find((c: any) => c.view === "minimum-distance").camera;
  const minDistance = Math.hypot(
    ...minimum.position.map((p: number, i: number) => p - minimum.target[i]),
  );
  const directions = views.map((v) =>
    normalize(v.target.map((t: number, i: number) => t - v.position[i])),
  );

  const license = new TextEncoder().encode(
    licenseText("src/assets/river-props.ts", 20261010),
  );
  const members = new Map<string, Uint8Array>([
    [`${spec.id}-full.f32`, full],
    [`${spec.id}-coarse.f32`, coarse],
    ["license.txt", license],
  ]);
  const files = [...members].map(([path, bytes]) => ({
    path,
    bytes: bytes.length,
    sha256: sha(bytes),
  }));
  const operations = ["place", "rotate", "remove"];
  const draft = {
    ...candidate,
    id: spec.id,
    contentVersion: "pending",
    category: spec.category,
    tags: ["procedural", "starter-example"],
    environments: spec.environments,
    files,
    resources: {
      ...candidate.resources,
      cpuSourceBytes: files.reduce((sum, f) => sum + f.bytes, 0),
    },
    gaussian: {
      ...candidate.gaussian,
      full: {
        ...candidate.gaussian.full,
        quality: { status: "unreviewed", report: null },
      },
      coarse: {
        ...candidate.gaussian.coarse,
        quality: { status: "unreviewed", report: null },
      },
      validatedDistance: [minDistance, 15],
      validatedDirections: directions,
    },
    provenance: {
      author: "Project procedural generator",
      source: "src/assets/river-props.ts",
      license: {
        id: LICENSE_ID,
        summary: LICENSE_SUMMARY,
        evidence: "license.txt",
        attribution: "Gaussian Scene Studio procedural generator",
        redistributable: true,
        redistributionBasis: LICENSE_BASIS,
      },
      changes: `Seed 20261010, kind ${spec.kind}; point data identical to candidate ${spec.candidate}. Renamed for the starter library.`,
      derivedFrom: [],
    },
    quality: {
      status: "candidate",
      report: REPORT,
      limitations: LIMITATIONS,
      inspectionViews: [],
      operations: [],
      humanReview: null,
    },
    object: {
      ...candidate.object,
      maxSlopeDegrees: 10,
      rotation: "upright-yaw",
      verifiedYawDegrees: [0, 180],
    },
  };
  draft.contentVersion = await assetContentVersion(parseAssetManifest(draft));
  const manifest = parseAssetManifest(draft);
  const bytes = await prepareAssetPackage(manifest, members);
  const passed = { status: "passed", report: REPORT };
  const review = {
    format: "general-scene-asset-review",
    version: 1,
    evidenceKind: "human",
    asset: { id: manifest.id, contentVersion: manifest.contentVersion },
    files: manifest.files.map(({ path, sha256 }) => ({ path, sha256 })),
    quality: {
      status: "accepted",
      report: REPORT,
      limitations: LIMITATIONS,
      inspectionViews: views,
      operations,
      humanReview: {
        reviewer: REVIEWER,
        reviewedAt: REVIEWED_AT,
        asset: { id: manifest.id, contentVersion: manifest.contentVersion },
        files: manifest.files.map(({ path, sha256 }) => ({ path, sha256 })),
        operations,
      },
    },
    full: passed,
    coarse: passed,
  };
  await registerAsset({ root: out, packageBytes: bytes, review });
  reviewed.push(`${manifest.id} ${manifest.contentVersion}`);
}

// Surface style: same parameters as the 2026-10-13 surface inspection run.
const surfaceRun = join(
  resolve(from, ".."),
  "general-surface-reviews/2026-10-13T11-46-14.862Z/evidence.json",
);
const surfaceEvidence = JSON.parse(readFileSync(surfaceRun, "utf8"));
const surfaceViews = [
  ...new Set<string>(
    surfaceEvidence.cases
      .flatMap((c: any) => c.captures)
      .filter((c: any) => c.kind === "normal")
      .map((c: any) => JSON.stringify(c.camera)),
  ),
]
  .slice(0, 32)
  .map((c) => JSON.parse(c));
const styleDraft = {
  id: "starter-surface-v1",
  contentVersion: "pending",
  parameters: {
    "sampler-version": 1,
    "tangent-scale": 0.7,
    "normal-scale": 0.1,
    opacity: 1,
    "terrain-color": [0.18, 0.23, 0.09],
    "water-color": [0.025, 0.16, 0.21],
    "color-variation": 0.12,
    "shore-step": 0.5,
  },
  quality: {
    status: "candidate",
    report: REPORT,
    limitations: [
      "Starter example: flat-colored procedural ground and water, not a photographic surface.",
      "Approved from the flat, slope and mild-river inspection captures.",
    ],
    inspectionViews: [],
    operations: [],
    humanReview: null,
  },
  provenance: {
    author: "项目程序表面（入门示例）",
    source: "src/general-scene/surface.ts",
    license: {
      id: LICENSE_ID,
      summary: LICENSE_SUMMARY,
      evidence: "starter-library/LICENSE.txt",
      attribution: "Gaussian Scene Studio procedural surface sampler",
      redistributable: true,
      redistributionBasis: LICENSE_BASIS,
    },
    changes:
      "Parameters identical to the 2026-10-13 general-surface-inspection-v1 run.",
    derivedFrom: [],
  },
};
const contentVersion = await styleContentVersion(parseSurfaceStyle(styleDraft));
const style = parseSurfaceStyle({
  ...styleDraft,
  contentVersion,
  quality: {
    ...styleDraft.quality,
    status: "accepted",
    inspectionViews: surfaceViews,
    operations: ["browse"],
    humanReview: {
      reviewer: REVIEWER,
      reviewedAt: REVIEWED_AT,
      asset: { id: styleDraft.id, contentVersion },
      files: [{ path: "style-identity.json", sha256: contentVersion.slice(7) }],
      operations: ["browse"],
    },
  },
});
const indexPath = join(out, "index.json"),
  index = JSON.parse(readFileSync(indexPath, "utf8"));
writeFileSync(indexPath, canonicalJson({ ...index, styles: [style] }) + "\n");
writeFileSync(
  join(out, "LICENSE.txt"),
  licenseText(
    "src/assets/river-props.ts and src/general-scene/surface.ts",
    20261010,
  ),
);
reviewed.push(`${style.id} ${style.contentVersion}`);

const library = await loadLibrary(indexPath);
console.log(
  JSON.stringify(
    {
      digest: library.digest,
      assets: library.manifests.map((m) => [m.id, m.quality.status]),
      styles: library.styles.map((s) => [s.id, s.quality.status]),
      reviewed,
    },
    null,
    2,
  ),
);
